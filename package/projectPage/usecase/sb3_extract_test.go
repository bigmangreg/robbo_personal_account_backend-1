func TestValidateSb3Archive_rejectsNonZip(t *testing.T) {
	err := validateSb3Archive([]byte(`{"targets":[]}`))
	if !errors.Is(err, projectPage.ErrBadRequest) {
		t.Fatalf("expected ErrBadRequest, got %v", err)
	}
}
